/**
 * Generates scripts/create-admin.sql with a bcrypt-hashed password so the
 * first admin account can be created via `npm run create-admin:local` /
 * `npm run create-admin`.
 *
 * Usage:
 *   node scripts/generate-admin-sql.js "admin@yogafitwithmeenu.online" "YourStrongPassword123" "Meenu"
 *
 * Never commit the generated create-admin.sql file if it contains a
 * password you plan to keep secret — it holds only the bcrypt hash (not the
 * plaintext password), but treat it as sensitive anyway and delete it after
 * running the migration.
 */

const bcrypt = require("bcryptjs");
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const [, , email, password, name] = process.argv;

if (!email || !password) {
  console.error(
    "Usage: node scripts/generate-admin-sql.js <email> <password> [name]"
  );
  process.exit(1);
}

if (password.length < 10) {
  console.error("Password must be at least 10 characters.");
  process.exit(1);
}

const hash = bcrypt.hashSync(password, 12);
const id = crypto.randomUUID();
const displayName = name || "Admin";

const sql = `-- Auto-generated by scripts/generate-admin-sql.js
-- Creates (or updates) the first admin user.
INSERT INTO users (id, email, password_hash, name, role, is_active)
VALUES ('${id}', '${email.toLowerCase()}', '${hash}', '${displayName.replace(/'/g, "''")}', 'admin', 1)
ON CONFLICT(email) DO UPDATE SET
  password_hash = excluded.password_hash,
  name = excluded.name,
  role = 'admin',
  is_active = 1,
  updated_at = datetime('now');
`;

const outPath = path.join(__dirname, "create-admin.sql");
fs.writeFileSync(outPath, sql, "utf8");
console.log(`Written to ${outPath}`);
console.log("Now run: npm run create-admin:local   (or npm run create-admin for production)");
